// ===== 工具函数 =====

// 格式化日期
function formatDate(dateStr) {
  if (!dateStr) return '-';
  const d = new Date(dateStr);
  const year = d.getFullYear();
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  const hour = String(d.getHours()).padStart(2, '0');
  const min = String(d.getMinutes()).padStart(2, '0');
  return `${year}-${month}-${day} ${hour}:${min}`;
}

// 格式化短日期
function formatShortDate(dateStr) {
  if (!dateStr) return '-';
  const d = new Date(dateStr);
  const month = String(d.getMonth() + 1).padStart(2, '0');
  const day = String(d.getDate()).padStart(2, '0');
  return `${d.getFullYear()}-${month}-${day}`;
}

// 截断文本
function truncate(str, len) {
  if (!str) return '';
  return str.length > len ? str.substring(0, len) + '...' : str;
}

// 简单 Markdown 转 HTML
function markdownToHtml(md) {
  if (!md) return '';
  let html = md;
  // 代码块
  html = html.replace(/```(\w*)\n([\s\S]*?)```/g, '<pre><code>$2</code></pre>');
  // 行内代码
  html = html.replace(/`([^`]+)`/g, '<code>$1</code>');
  // 标题
  html = html.replace(/^### (.+)$/gm, '<h3>$1</h3>');
  html = html.replace(/^## (.+)$/gm, '<h2>$1</h2>');
  html = html.replace(/^# (.+)$/gm, '<h1>$1</h1>');
  // 粗体和斜体
  html = html.replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>');
  html = html.replace(/\*(.+?)\*/g, '<em>$1</em>');
  // 引用
  html = html.replace(/^> (.+)$/gm, '<blockquote>$1</blockquote>');
  // 无序列表
  html = html.replace(/^- (.+)$/gm, '<li>$1</li>');
  html = html.replace(/(<li>.*<\/li>\n?)+/g, '<ul>$&</ul>');
  // 段落
  html = html.replace(/\n\n/g, '</p><p>');
  html = '<p>' + html + '</p>';
  // 清理
  html = html.replace(/<p><\/p>/g, '');
  html = html.replace(/<p>(<h[1-3]>)/g, '$1');
  html = html.replace(/(<\/h[1-3]>)<\/p>/g, '$1');
  html = html.replace(/<p>(<pre>)/g, '$1');
  html = html.replace(/(<\/pre>)<\/p>/g, '$1');
  html = html.replace(/<p>(<ul>)/g, '$1');
  html = html.replace(/(<\/ul>)<\/p>/g, '$1');
  html = html.replace(/<p>(<blockquote>)/g, '$1');
  html = html.replace(/(<\/blockquote>)<\/p>/g, '$1');
  return html;
}

// 防抖
function debounce(fn, delay) {
  let timer;
  return function (...args) {
    clearTimeout(timer);
    timer = setTimeout(() => fn.apply(this, args), delay);
  };
}

// 获取名字首字母
function getInitials(name) {
  if (!name) return '?';
  return name.charAt(0).toUpperCase();
}

// 更新时间显示
function updateClock() {
  const el = document.getElementById('currentTime');
  if (el) {
    const now = new Date();
    const options = { year: 'numeric', month: '2-digit', day: '2-digit', weekday: 'short', hour: '2-digit', minute: '2-digit' };
    el.textContent = now.toLocaleDateString('zh-CN', options);
  }
}

// 自定义下拉框
function toggleCustomSelect(id) {
  const el = document.getElementById(id);
  if (!el) return;
  const trigger = el.querySelector('.custom-select-trigger');
  const dropdown = el.querySelector('.custom-select-dropdown');
  const isOpen = dropdown.classList.contains('open');
  // 先关闭所有
  closeAllCustomSelects();
  if (!isOpen) {
    dropdown.classList.add('open');
    trigger.classList.add('active');
    // 让 modal-body 不裁剪下拉框
    const modalBody = el.closest('.modal-body');
    if (modalBody) modalBody.classList.add('dropdown-open');
  }
}

function closeAllCustomSelects() {
  document.querySelectorAll('.custom-select-dropdown.open').forEach(d => {
    d.classList.remove('open');
    d.parentElement.querySelector('.custom-select-trigger').classList.remove('active');
  });
  document.querySelectorAll('.modal-body.dropdown-open').forEach(mb => {
    mb.classList.remove('dropdown-open');
  });
}

function selectCustomOption(selectId, value, label) {
  const el = document.getElementById(selectId);
  if (!el) return;
  // 更新 hidden input
  const hiddenInput = el.parentElement.querySelector('input[type="hidden"]');
  if (hiddenInput) hiddenInput.value = value;
  // 更新显示
  const labelEl = el.querySelector('.custom-select-trigger span');
  if (labelEl) labelEl.textContent = label;
  // 更新选中状态
  el.querySelectorAll('.custom-select-option').forEach(opt => {
    opt.classList.toggle('selected', opt.dataset.value === value);
  });
  // 关闭下拉
  closeAllCustomSelects();
}

// 点击外部关闭下拉框
document.addEventListener('click', function(e) {
  if (!e.target.closest('.custom-select')) {
    closeAllCustomSelects();
  }
});

